-- =========================================================
-- 1. Task 主表
-- 保存 Task 的通用业务属性，不保存动态表单字段
-- =========================================================

CREATE TABLE task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    task_key VARCHAR(100) NOT NULL UNIQUE,

    title VARCHAR(255) NOT NULL,

    description TEXT,

    status VARCHAR(20) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN (
            'OPEN',
            'IN_PROGRESS',
            'COMPLETED',
            'CANCELLED'
        )),

    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM'
        CHECK (priority IN (
            'LOW',
            'MEDIUM',
            'HIGH',
            'URGENT'
        )),

    assigned_to VARCHAR(100),

    created_by VARCHAR(100) NOT NULL,

    due_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE task IS 'Task 主表，保存任务的通用业务属性';
COMMENT ON COLUMN task.id IS 'Task 主键';
COMMENT ON COLUMN task.task_key IS 'Task 业务唯一标识';
COMMENT ON COLUMN task.title IS 'Task 标题';
COMMENT ON COLUMN task.description IS 'Task 描述';
COMMENT ON COLUMN task.status IS 'Task 状态：OPEN、IN_PROGRESS、COMPLETED、CANCELLED';
COMMENT ON COLUMN task.priority IS 'Task 优先级：LOW、MEDIUM、HIGH、URGENT';
COMMENT ON COLUMN task.assigned_to IS '被分配用户的标识';
COMMENT ON COLUMN task.created_by IS '创建者的用户标识';
COMMENT ON COLUMN task.due_at IS 'Task 截止时间';
COMMENT ON COLUMN task.created_at IS '创建时间';
COMMENT ON COLUMN task.updated_at IS '最后更新时间';


-- =========================================================
-- 2. Task Template 主表
-- 保存模板元信息和当前生效版本的引用
-- =========================================================

CREATE TABLE task_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    template_key VARCHAR(100) NOT NULL UNIQUE,

    name VARCHAR(255) NOT NULL,

    description TEXT,

    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN (
            'DRAFT',
            'ACTIVE',
            'INACTIVE'
        )),

    current_version_id BIGINT,

    created_by VARCHAR(100) NOT NULL,

    updated_by VARCHAR(100) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE task_template IS 'Task 模板主表，管理模板元信息、整体状态和当前版本';
COMMENT ON COLUMN task_template.id IS '模板主键';
COMMENT ON COLUMN task_template.template_key IS '模板业务唯一标识，创建后原则上不修改';
COMMENT ON COLUMN task_template.name IS '模板名称';
COMMENT ON COLUMN task_template.description IS '模板描述';
COMMENT ON COLUMN task_template.status IS '模板状态：DRAFT（草稿）、ACTIVE（启用）、INACTIVE（停用）';
COMMENT ON COLUMN task_template.current_version_id IS '当前用于创建新 Task 的已发布模板版本 ID';
COMMENT ON COLUMN task_template.created_by IS '模板创建者的用户标识';
COMMENT ON COLUMN task_template.updated_by IS '最后修改者的用户标识';
COMMENT ON COLUMN task_template.created_at IS '创建时间';
COMMENT ON COLUMN task_template.updated_at IS '最后更新时间';


-- =========================================================
-- 3. Task Template Version 版本表
-- 每个版本保存独立的表单 Schema 和 UI 配置
-- =========================================================

CREATE TABLE task_template_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    template_id BIGINT NOT NULL,

    version_number INTEGER NOT NULL
        CHECK (version_number > 0),

    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN (
            'DRAFT',
            'PUBLISHED',
            'RETIRED'
        )),

    schema_json JSONB NOT NULL,

    ui_schema_json JSONB NOT NULL DEFAULT '{}'::JSONB,

    created_by VARCHAR(100) NOT NULL,

    published_by VARCHAR(100),

    published_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_template_version_template
        FOREIGN KEY (template_id)
        REFERENCES task_template(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_template_version_number
        UNIQUE (template_id, version_number),

    -- 供模板表使用复合外键，保证当前版本属于对应模板
    CONSTRAINT uq_template_version_template_id
        UNIQUE (template_id, id),

    CONSTRAINT ck_template_version_schema_object
        CHECK (jsonb_typeof(schema_json) = 'object'),

    CONSTRAINT ck_template_version_ui_schema_object
        CHECK (jsonb_typeof(ui_schema_json) = 'object'),

    CONSTRAINT ck_template_version_publish_info
        CHECK (
            (status = 'DRAFT'
                AND published_at IS NULL
                AND published_by IS NULL)
            OR
            (status IN ('PUBLISHED', 'RETIRED')
                AND published_at IS NOT NULL
                AND published_by IS NOT NULL)
        )
);

COMMENT ON TABLE task_template_version IS 'Task 模板版本表，保存每个版本不可变的表单定义';
COMMENT ON COLUMN task_template_version.id IS '模板版本主键';
COMMENT ON COLUMN task_template_version.template_id IS '所属模板 ID';
COMMENT ON COLUMN task_template_version.version_number IS '模板版本号，从 1 开始，在同一模板内递增';
COMMENT ON COLUMN task_template_version.status IS '版本状态：DRAFT（草稿）、PUBLISHED（已发布）、RETIRED（历史版本）';
COMMENT ON COLUMN task_template_version.schema_json IS '表单字段及数据结构定义，JSON Schema 格式或约定的 Schema 格式';
COMMENT ON COLUMN task_template_version.ui_schema_json IS '表单 UI 配置，例如字段布局、展示顺序、组件属性等';
COMMENT ON COLUMN task_template_version.created_by IS '版本创建者的用户标识';
COMMENT ON COLUMN task_template_version.published_by IS '发布者的用户标识';
COMMENT ON COLUMN task_template_version.published_at IS '首次发布时间';
COMMENT ON COLUMN task_template_version.created_at IS '版本创建时间';
COMMENT ON COLUMN task_template_version.updated_at IS '最后更新时间';


-- =========================================================
-- 4. 为模板的当前版本建立复合外键
-- 保证 current_version_id 对应的版本属于该模板
-- =========================================================

ALTER TABLE task_template
    ADD CONSTRAINT fk_template_current_version
    FOREIGN KEY (id, current_version_id)
    REFERENCES task_template_version (template_id, id)
    ON DELETE RESTRICT;


-- =========================================================
-- 5. 同一个模板最多只能有一个 PUBLISHED 版本
-- =========================================================

CREATE UNIQUE INDEX uq_template_one_published_version
    ON task_template_version (template_id)
    WHERE status = 'PUBLISHED';


-- =========================================================
-- 6. Task 动态表单数据表
-- 每个 Task 最多关联一条动态表单数据
-- =========================================================

CREATE TABLE task_extra_data (
    task_id BIGINT PRIMARY KEY,

    template_version_id BIGINT NOT NULL,

    data_json JSONB NOT NULL DEFAULT '{}'::JSONB,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_task_extra_data_task
        FOREIGN KEY (task_id)
        REFERENCES task(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_task_extra_data_template_version
        FOREIGN KEY (template_version_id)
        REFERENCES task_template_version(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_task_extra_data_json_object
        CHECK (jsonb_typeof(data_json) = 'object')
);

COMMENT ON TABLE task_extra_data IS 'Task 动态表单数据表，保存用户填写的数据及其模板版本引用';
COMMENT ON COLUMN task_extra_data.task_id IS '关联的 Task ID，同时作为本表主键';
COMMENT ON COLUMN task_extra_data.template_version_id IS '创建该 Task 时使用的模板版本 ID';
COMMENT ON COLUMN task_extra_data.data_json IS '用户填写的动态表单数据，JSON 对象格式';
COMMENT ON COLUMN task_extra_data.created_at IS '动态表单数据创建时间';
COMMENT ON COLUMN task_extra_data.updated_at IS '动态表单数据最后更新时间';


-- =========================================================
-- 7. 常用查询索引
-- =========================================================

-- 按负责人及状态查询 Task
CREATE INDEX idx_task_assigned_to_status
    ON task (assigned_to, status);

-- 按截止时间查询 Task
CREATE INDEX idx_task_due_at
    ON task (due_at)
    WHERE due_at IS NOT NULL;

-- 按模板状态查询模板列表
CREATE INDEX idx_task_template_status_updated_at
    ON task_template (status, updated_at DESC);

-- 查询模板下的全部版本
CREATE INDEX idx_task_template_version_template_created
    ON task_template_version (template_id, created_at DESC);

-- 查询引用某一模板版本的 Task
CREATE INDEX idx_task_extra_data_template_version
    ON task_extra_data (template_version_id);

-- 动态表单 JSONB 查询索引
-- 如果经常使用 @>、? 等 JSONB 操作符查询 data_json，可保留此索引。
-- 如果 JSONB 查询很少，可以先不创建。
CREATE INDEX idx_task_extra_data_data_json_gin
    ON task_extra_data
    USING GIN (data_json);